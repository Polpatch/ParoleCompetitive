import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const read = (path) => readFile(new URL(`../data/${path}`, import.meta.url), 'utf8');
const [source, common, expanded, additions, exclusions, reviewed] = await Promise.all([
  read('upstream/60000_parole_italiane.txt'),
  read('upstream/1000_parole_italiane_comuni.txt'),
  read('upstream/660000_parole_italiane.txt'),
  read('additions.txt'),
  read('exclusions.txt'),
  read('solutions-v1.txt'),
]);
const normalize = (text) => [...new Set(text.split(/\r?\n/).filter((word) => /^[a-zA-Z]{5}$/.test(word)).map((word) => word.toUpperCase()))].sort();
const previous = normalize(source + '\n' + common);
const excluded = new Set(normalize(exclusions));
if (previous.some(word => excluded.has(word))) throw new Error('An exclusion would remove a previously allowed guess');
const allowed = normalize([source, common, expanded, additions].join('\n')).filter(word => !excluded.has(word));
const solutions = reviewed.trim().split(/\r?\n/);
if (solutions.some(word => !allowed.includes(word)) || new Set(solutions).size !== solutions.length) {
  throw new Error('Historical solutions must be unique words present in the allowed dictionary');
}
const vocabularyId = createHash('sha256').update(allowed.join('\n') + '\n').digest('hex');
const output = `// Generated by scripts/generate-words.mjs. Do not edit.\nexport const allowedWords = ${JSON.stringify(allowed)};\nexport const solutionsV1 = ${JSON.stringify(solutions)};\nexport const vocabularyId = ${JSON.stringify(vocabularyId)};\n`;
await writeFile(new URL('../src/word-data.ts', import.meta.url), output);
