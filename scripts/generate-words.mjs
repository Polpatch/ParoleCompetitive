import { readFile, writeFile } from 'node:fs/promises';

const source = await readFile(new URL('../data/upstream/60000_parole_italiane.txt', import.meta.url), 'utf8');
const common = await readFile(new URL('../data/upstream/1000_parole_italiane_comuni.txt', import.meta.url), 'utf8');
const reviewed = await readFile(new URL('../data/solutions-v1.txt', import.meta.url), 'utf8');
const normalize = (text) => [...new Set(text.split(/\r?\n/).filter((word) => /^[a-zA-Z]{5}$/.test(word)).map((word) => word.toUpperCase()))].sort();
const allowed = normalize(source + '\n' + common);
const candidates = new Set(normalize(common));
const solutions = reviewed.trim().split(/\r?\n/);
if (solutions.some((word) => !candidates.has(word) || !allowed.includes(word)) || new Set(solutions).size !== solutions.length) {
  throw new Error('Reviewed solutions must be unique common words present in the allowed dictionary');
}
const output = `// Generated by scripts/generate-words.mjs. Do not edit.\nexport const allowedWords = ${JSON.stringify(allowed)};\nexport const solutionsV1 = ${JSON.stringify(solutions)};\n`;
await writeFile(new URL('../src/word-data.ts', import.meta.url), output);
