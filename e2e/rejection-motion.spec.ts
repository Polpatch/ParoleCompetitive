import { expect, test } from '@playwright/test';
import { evaluateGuess, hardConstraints } from '../src/game';
import { allowedWords } from '../src/word-data';

const key = 'parolecompetitive:session:v1';
const date = '2026-03-10';

test('rejections restart only the active row and do not block editing or reveal', async ({ page }) => {
  const now = new Date(`${date}T12:00:00Z`);
  await page.clock.install({ time: now });
  await page.clock.pauseAt(now);
  await page.goto('/ParoleCompetitive/');
  await expect(page.getByRole('button', { name: 'Invio' })).toBeEnabled();
  const game = () => page.evaluate(({ key, date }) => JSON.parse(localStorage.getItem(key)!).games[date], { key, date });
  await expect.poll(async () => (await game())?.solution).toBeTruthy();
  const initial = await game();
  await page.keyboard.press('Enter');
  await expect(page.locator('.toast')).toContainText('Servono 5 lettere dalla A alla Z');
  await expect(page.locator('.tile.rejected')).toHaveCount(5);
  expect(await game()).toEqual(initial);
  await page.clock.runFor(200);
  await page.keyboard.press('Enter');
  await expect(page.locator('.tile.rejected')).toHaveCount(5);
  await page.keyboard.type('ZZZZZ');
  await expect.poll(async () => (await game()).draft).toBe('ZZZZZ');
  await page.keyboard.press('Enter');
  await expect(page.locator('.toast')).toContainText('Parola non ammessa');
  expect((await game()).startedAt).toBeNull();
  for (let i = 0; i < 5; i++) await page.keyboard.press('Backspace');
  const wrong = allowedWords.find(word => word !== initial.solution)!;
  await page.keyboard.type(wrong);
  await page.keyboard.press('Enter');
  await expect(page.locator('.tile.revealing')).toHaveCount(5);
  await expect(page.locator('.tile.rejected')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Invio' })).toBeDisabled();
  await page.clock.runFor(2200);
  await expect(page.getByRole('button', { name: 'Invio' })).toBeEnabled();
  await page.keyboard.press('Enter');
  await expect(page.locator('.tile.rejected')).toHaveCount(5);
  await expect(page.locator('.tile').nth(5)).toHaveClass(/rejected/);
  await page.clock.setFixedTime(new Date('2026-03-11T12:00:00Z'));
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  await expect.poll(() => page.evaluate(key => !!JSON.parse(localStorage.getItem(key)!).games['2026-03-11'], key)).toBe(true);
  await expect(page.locator('.tile').first()).toHaveText('');
  await expect(page.getByRole('button', { name: 'Invio' })).toBeEnabled();
  await expect(page.locator('.tile.rejected')).toHaveCount(0);
});

test('hard-mode clue rejection moves the active row without changing the game', async ({ page }) => {
  const now = new Date(`${date}T12:00:00Z`);
  await page.clock.install({ time: now });
  await page.clock.pauseAt(now);
  await page.goto('/ParoleCompetitive/');
  await expect(page.getByRole('button', { name: 'Invio' })).toBeEnabled();
  const game = () => page.evaluate(({ key, date }) => JSON.parse(localStorage.getItem(key)!).games[date], { key, date });
  await expect.poll(async () => (await game())?.solution).toBeTruthy();
  const { solution } = await game();
  const first = allowedWords.find(word => word !== solution && evaluateGuess(solution, word).includes('green'))!;
  const feedback = evaluateGuess(solution, first);
  const gray = new Set([...first].filter((letter, i) => feedback[i] === 'gray' && !feedback.some((value, j) => first[j] === letter && value !== 'gray')));
  const constraints = hardConstraints([{ word: first, feedback }]);
  const invalid = allowedWords.find(word => ![...word].some(letter => gray.has(letter)) && constraints.green.some((letter, i) => letter && word[i] !== letter))!;
  expect(invalid).toBeTruthy();
  await page.getByRole('button', { name: 'Apri menu' }).click();
  await page.clock.runFor(200);
  await page.getByRole('button', { name: 'Impostazioni', exact: true }).click();
  await page.getByLabel('Difficile', { exact: true }).check();
  await expect.poll(async () => (await game()).hard).toBe(true);
  await page.getByRole('button', { name: 'Chiudi finestra', exact: true }).click();
  await page.getByRole('button', { name: 'Apri menu' }).blur();
  await page.keyboard.type(first);
  await page.keyboard.press('Enter');
  await expect(page.locator('.tile.revealing')).toHaveCount(5);
  await page.clock.runFor(2200);
  await page.keyboard.type(invalid);
  await expect.poll(async () => (await game()).draft).toBe(invalid);
  const before = await game();
  await page.keyboard.press('Enter');
  await expect(page.locator('.toast')).toContainText('Rispetta gli indizi della modalità difficile');
  await expect(page.locator('.tile.rejected')).toHaveCount(5);
  await expect(page.locator('.tile').nth(5)).toHaveClass(/rejected/);
  expect(await game()).toEqual(before);
});

test('reduced motion retains rejection feedback without animation or input delay', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.clock.setFixedTime(new Date(`${date}T12:00:00Z`));
  await page.goto('/ParoleCompetitive/');
  await expect(page.getByRole('button', { name: 'Invio' })).toBeEnabled();
  await page.keyboard.press('Enter');
  await expect(page.locator('.toast')).toContainText('Servono 5 lettere dalla A alla Z');
  await expect(page.locator('.tile.rejected')).toHaveCount(0);
  await page.keyboard.type('A');
  await expect(page.locator('.tile').first()).toHaveText('A');
});
